function buildSupplementaryPrompt(tableIds, data) {
  const ddls  = (data.source_table_ddl  || []).filter(d => !d.retiring_timestamp);
  const prof  = (data.field_profiling   || []).filter(p => !p.retiring_timestamp);
  const lines = [
    'SUPPLEMENTARY CONTEXT -- please incorporate into our ongoing conversation',
    '',
    'The steward has provided additional data structure information:',
    '',
  ];

  tableIds.forEach(id => {
    const ddl = ddls.find(d => d.source_table_ddl_id === id);
    if (!ddl) return;
    lines.push('### ' + ddl.source_table_name);
    let cols = [];
    try { cols = ddl.parsed_columns ? JSON.parse(ddl.parsed_columns) : []; } catch {}
    if (cols.length > 0) {
      cols.forEach(c => lines.push(c.name + '  ' + c.type));
    }
    lines.push('');
    const tableProf = prof.filter(p =>
      p.source_database_name === ddl.source_database_name &&
      p.source_table_name    === ddl.source_table_name
    );
    if (tableProf.length > 0) {
      lines.push('Data profiling for ' + ddl.source_table_name + ':');
      tableProf.forEach(p => {
        lines.push('Field: ' + (p.source_field_name || 'unknown'));
        if (p.summary_raw) lines.push(p.summary_raw);
        lines.push('');
      });
    }
  });

  lines.push('Please continue the conversation with this additional context in mind.');
  return lines.join('\n');
}

