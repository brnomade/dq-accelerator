function Stage4Panel({ proposals, validations, onCommit, onRefine, onUpdate, onDiscard, data }) {
  const uncommitted = proposals.filter(p => !p.committed);

  if (proposals.length === 0) {
    return (
      <div className="status-row status-info" style={{ marginBottom:16 }}>
        No proposals to review. Go back to Step 3 and parse the AI output.
      </div>
    );
  }

  return (
    <div>
      <div style={{ display:'flex', alignItems:'center', gap:10, marginBottom:20 }}>
        <div className="page-title" style={{ marginBottom:0 }}>
          Review {proposals.length} rule proposal{proposals.length !== 1 ? 's' : ''}
        </div>
        {uncommitted.length > 0 && (
          <span className="badge badge-amber">{uncommitted.length} pending</span>
        )}
        {uncommitted.length === 0 && proposals.length > 0 && (
          <span className="badge badge-green">All committed</span>
        )}
      </div>

      {proposals.map((p, i) => (
        <ProposalReviewCard
          key={i}
          index={i}
          proposal={p}
          validation={validations[i] || { gaps:[], staleIds:[], warns:[] }}
          onCommit={onCommit}
          onRefine={onRefine}
          onUpdate={onUpdate}
          onDiscard={onDiscard}
          data={data}
        />
      ))}
    </div>
  );
}

