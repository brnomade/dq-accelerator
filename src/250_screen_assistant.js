const ASSISTANT_STORAGE_KEY = 'moj_dq_assistant_v1';
const PROMPT_VERSION        = 'BRA-2';

// ===============================================================================
// G1.2 -- STORAGE
// ===============================================================================

function loadAssistantState() {
  try {
    const raw = localStorage.getItem(ASSISTANT_STORAGE_KEY);
    if (!raw) return null;
    const s = JSON.parse(raw);
    return {
      rule_intent:       s.rule_intent       || '',
      cde_ids:           s.cde_ids           || [],
      extra_table_ids:   s.extra_table_ids   || [],
      conversation_mode: s.conversation_mode || 'business',
      proposals:         s.proposals         || [],
      saved_at:          s.saved_at          || null,
    };
  } catch { return null; }
}

function saveAssistantState(state) {
  try {
    localStorage.setItem(ASSISTANT_STORAGE_KEY, JSON.stringify({
      rule_intent:       state.rule_intent       || '',
      cde_ids:           state.cde_ids           || [],
      extra_table_ids:   state.extra_table_ids   || [],
      conversation_mode: state.conversation_mode || 'business',
      proposals:         state.proposals         || [],
      saved_at:          new Date().toISOString(),
    }));
    window.dispatchEvent(new Event('storage'));
  } catch {}
}

function clearAssistantState() {
  try {
    localStorage.removeItem(ASSISTANT_STORAGE_KEY);
    window.dispatchEvent(new Event('storage'));
  } catch {}
}

