// G4.2 -- PROPOSAL PARSER
// ===============================================================================

function parseProposals(text) {
  if (!text || !text.trim()) return { proposals: [], notFound: true };

  const startDelim = '===RULE_PROPOSAL_START===';
  const endDelim   = '===RULE_PROPOSAL_END===';

  const blocks = [];
  let searchFrom = 0;
  while (true) {
    const startIdx = text.indexOf(startDelim, searchFrom);
    if (startIdx === -1) break;
    const endIdx = text.indexOf(endDelim, startIdx + startDelim.length);
    if (endIdx === -1) break;
    blocks.push(text.substring(startIdx + startDelim.length, endIdx).trim());
    searchFrom = endIdx + endDelim.length;
  }

  if (blocks.length === 0) return { proposals: [], notFound: true };

  const proposals = [];
  const errors    = [];
  const now       = new Date().toISOString();

  blocks.forEach((block, i) => {
    try {
      const parsed = JSON.parse(block);
      proposals.push({
        ...parsed,
        parsed_at:  now,
        committed:  false,
      });
    } catch (e) {
      errors.push({ index: i, message: 'JSON parse error: ' + e.message, raw: block });
    }
  });

  // Version check
  let versionMismatch = false;
  const versionMatch = text.match(/PROMPT_VERSION:\s*(\S+)/);
  if (versionMatch && versionMatch[1] !== PROMPT_VERSION) {
    versionMismatch = true;
  }

  // Detect mode
  let detectedMode = null;
  const modeMatch = text.match(/CONVERSATION_MODE:\s*(\S+)/);
  if (modeMatch) detectedMode = modeMatch[1].toLowerCase();

  return { proposals, errors, versionMismatch, detectedMode };
}

// ===============================================================================
// G5.1 -- PROPOSAL VALIDATOR
// ===============================================================================

function validateProposal(proposal, data) {
  const gaps    = [];
  const staleIds = [];
  const warns   = [];

  if (!proposal.rule_name || !proposal.rule_name.trim()) {
    gaps.push('rule_name is missing');
  }
  if (!proposal.rule_narrative || !proposal.rule_narrative.trim()) {
    gaps.push('rule_narrative is missing (the plain language description of the rule)');
  }
  if (!proposal.sql_code || !proposal.sql_code.trim()) {
    gaps.push('sql_code is missing');
  } else if (!/select/i.test(proposal.sql_code)) {
    gaps.push('sql_code does not appear to contain a SELECT statement');
  }
  if (proposal.quality_dimension_id === undefined || proposal.quality_dimension_id === null) {
    gaps.push('quality_dimension_id is missing');
  }
  if (proposal.bumper_value === undefined || proposal.bumper_value === null) {
    gaps.push('bumper_value is missing');
  } else if (proposal.bumper_value < 0 || proposal.bumper_value > 1) {
    gaps.push('bumper_value must be between 0 and 1');
  }
  if (!proposal.frequency || !['daily','weekly','monthly'].includes(proposal.frequency)) {
    gaps.push('frequency must be one of: daily, weekly, monthly');
  }
  if (!proposal.cde_id && !proposal.cde_suggestion) {
    gaps.push('cde_id or cde_suggestion must be provided');
  }

  // Non-blocking warning for missing examples
  if (!proposal.rule_examples || !Array.isArray(proposal.rule_examples) || proposal.rule_examples.length === 0) {
    warns.push('rule_examples not provided -- the AI did not give examples of failing records');
  }

  // Stale ID checks
  if (proposal.quality_dimension_id) {
    const dims = data.quality_dimension || [];
    const found = dims.find(d =>
      d.quality_dimension_id === proposal.quality_dimension_id && !d.retiring_timestamp
    );
    if (!found) {
      staleIds.push('quality_dimension_id ' + proposal.quality_dimension_id + ' not found in current store');
    }
  }
  if (proposal.cde_id) {
    const cdes = data.critical_data_element || [];
    const found = cdes.find(c =>
      c.critical_data_element_id === proposal.cde_id && !c.retiring_timestamp
    );
    if (!found) {
      staleIds.push('cde_id ' + proposal.cde_id + ' not found in current store (may be retired or unknown)');
    }
  }

  return {
    valid:    gaps.length === 0,
    gaps,
    staleIds,
    warns,
  };
}

