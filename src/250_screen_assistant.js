function AssistantScreen() {
  const { data, canEdit, upsertRecord, nextPk, navigate } = useApp();
  const dp = !canEdit
    ? { style:{ opacity:0.4, pointerEvents:'none' },
        title:'Set your steward identity in Settings to use the DQ Assistant' }
    : {};

  // Load persisted state
  const [stage,            setStage]           = useState(1);
  const [conversationMode, setConversationMode] = useState('business');
  const [ruleIntent,       setRuleIntent]       = useState('');
  const [selectedCdeIds,   setSelectedCdeIds]   = useState([]);
  const [extraTableIds,    setExtraTableIds]    = useState([]);
  const [cdeSearch,        setCdeSearch]        = useState('');
  const [builtPrompt,      setBuiltPrompt]      = useState('');
  const [contextSummary,   setContextSummary]   = useState(null);
  const [pasteText,        setPasteText]        = useState('');
  const [parseResult,      setParseResult]      = useState(null);
  const [proposals,        setProposals]        = useState([]);
  const [copyConfirmed,    setCopyConfirmed]    = useState(false);
  const [loaded,           setLoaded]           = useState(false);

  // Load on mount
  useEffect(() => {
    const s = loadAssistantState();
    if (s) {
      setRuleIntent(s.rule_intent);
      setSelectedCdeIds(s.cde_ids);
      setExtraTableIds(s.extra_table_ids);
      setConversationMode(s.conversation_mode || 'business');
      if (s.proposals && s.proposals.length > 0) {
        // Validate loaded proposals against current store
        const validated = s.proposals.map(p => ({
          ...p,
          _validation: validateProposal(p, data || {}),
        }));
        setProposals(validated);
        const hasUncommitted = validated.some(p => !p.committed);
        if (hasUncommitted) setStage(4);
      }
    }
    setLoaded(true);
  }, []);

  // Auto-save on intent/scope changes (debounced)
  const saveTimerRef = useRef(null);
  useEffect(() => {
    if (!loaded) return;
    if (saveTimerRef.current) clearTimeout(saveTimerRef.current);
    saveTimerRef.current = setTimeout(() => {
      saveAssistantState({
        rule_intent:       ruleIntent,
        cde_ids:           selectedCdeIds,
        extra_table_ids:   extraTableIds,
        conversation_mode: conversationMode,
        proposals:         proposals,
      });
    }, 800);
    return () => clearTimeout(saveTimerRef.current);
  }, [ruleIntent, selectedCdeIds, extraTableIds, conversationMode, loaded]);

  // Immediate save on proposals change
  useEffect(() => {
    if (!loaded) return;
    saveAssistantState({
      rule_intent:       ruleIntent,
      cde_ids:           selectedCdeIds,
      extra_table_ids:   extraTableIds,
      conversation_mode: conversationMode,
      proposals,
    });
  }, [proposals, loaded]);

  // CDE suggestions (debounced)
  const [suggestions, setSuggestions] = useState([]);
  const suggTimerRef = useRef(null);
  useEffect(() => {
    if (suggTimerRef.current) clearTimeout(suggTimerRef.current);
    suggTimerRef.current = setTimeout(() => {
      setSuggestions(suggestCdes(ruleIntent, data));
    }, 300);
    return () => clearTimeout(suggTimerRef.current);
  }, [ruleIntent, data]);

  // Compute validations for proposals
  const validations = proposals.map(p => validateProposal(p, data || {}));

  const handleCdeToggle = (id) => {
    setSelectedCdeIds(prev =>
      prev.includes(id) ? prev.filter(x => x !== id) : [...prev, id]
    );
  };

  const handleExtraTableToggle = (id) => {
    setExtraTableIds(prev =>
      prev.includes(id) ? prev.filter(x => x !== id) : [...prev, id]
    );
  };

  const handleBuild = () => {
    if (!ruleIntent || ruleIntent.trim().length < 10 || !data) return;
    const result = buildAssistantPrompt(
      ruleIntent, selectedCdeIds, extraTableIds, conversationMode, data
    );
    setBuiltPrompt(result.promptText);
    setContextSummary({ ...result.contextSummary, characterCount: result.characterCount });
    setCopyConfirmed(false);
    setStage(2);
  };

  const handleCopy = () => {
    copyToClipboard(builtPrompt, () => {
      setCopyConfirmed(true);
      setTimeout(() => setCopyConfirmed(false), 3000);
    }, () => {});
  };

  const handleParse = () => {
    const result = parseProposals(pasteText);
    setParseResult(result);
    if (result.proposals && result.proposals.length > 0) {
      const withValidation = result.proposals.map(p => ({
        ...p,
        _validation: validateProposal(p, data || {}),
      }));
      setProposals(prev => {
        const uncommitted = prev.filter(p => !p.committed);
        // Merge: keep committed ones, replace uncommitted with newly parsed
        const committed   = prev.filter(p => p.committed);
        return [...committed, ...withValidation];
      });
      setStage(4);
    }
  };

  const handleAddContextCopy = (tableIds) => {
    const prompt = buildSupplementaryPrompt(tableIds, data);
    copyToClipboard(prompt, () => {}, () => {});
  };

  const handleCommit = (proposalIndex, proposal) => {
    if (!data || !canEdit) return;

    const ruleId  = nextPk('data_quality_rule');
    const allocId = nextPk('data_quality_rule_allocation');

    upsertRecord('data_quality_rule', {
      data_quality_rule_id: ruleId,
      rule_name:            proposal.rule_name,
      rule_explanation:     proposal.rule_narrative || proposal.rule_explanation || '',
      sql_code:             proposal.sql_code || '',
      sql_code_sample:      proposal.sql_code_sample || '',
      source_code_link:     '',
      automated:            proposal.automated !== false,
      retiring_timestamp:   null,
    });

    upsertRecord('data_quality_rule_allocation', {
      data_quality_rule_allocation_id: allocId,
      data_quality_rule_id:            ruleId,
      critical_data_element_id:        proposal.cde_id,
      quality_dimension_id:            proposal.quality_dimension_id,
      bumper_value:                    proposal.bumper_value,
      frequency:                       proposal.frequency || 'daily',
      retiring_timestamp:              null,
    });

    setProposals(prev => prev.map((p, i) =>
      i === proposalIndex
        ? { ...p, committed: true, _createdRuleId: ruleId, _createdAllocId: allocId }
        : p
    ));
  };

  const handleRefine = (proposalIndex, proposal) => {
    const v = validateProposal(proposal, data || {});
    const gaps = [...v.gaps, ...v.staleIds];
    const prompt = buildRefinementPrompt(proposal, gaps.length > 0 ? gaps : ['Please review and improve the proposal']);
    copyToClipboard(prompt, () => {}, () => {});
    setPasteText('');
    setParseResult(null);
    setStage(3);
  };

  const handleUpdateProposal = (index, updated) => {
    setProposals(prev => prev.map((p, i) => i === index ? { ...updated } : p));
  };

  const handleDiscardProposal = (index) => {
    if (window.confirm('Discard this proposal?')) {
      setProposals(prev => prev.filter((_, i) => i !== index));
    }
  };

  const handleStartNew = () => {
    if (window.confirm('Start a new conversation? This will clear your current rule and any uncommitted proposals.')) {
      clearAssistantState();
      setStage(1);
      setRuleIntent('');
      setSelectedCdeIds([]);
      setExtraTableIds([]);
      setConversationMode('business');
      setCdeSearch('');
      setBuiltPrompt('');
      setContextSummary(null);
      setPasteText('');
      setParseResult(null);
      setProposals([]);
      setCopyConfirmed(false);
    }
  };

  const accentColor = 'var(--accent)';

  return (
    <div className="fade-in">
      {/* Title row */}
      <div style={{ display:'flex', alignItems:'flex-start', justifyContent:'space-between', marginBottom:8 }}>
        <div>
          <div className="page-title">DQ Assistant</div>
          <div className="page-sub">
            Define quality rules with AI help. Build a prompt, copy to your AI tool, paste the result back.
          </div>
        </div>
        <button className="btn btn-ghost" style={{ fontSize:12, marginTop:4 }}
          onClick={handleStartNew}>
          Start new
        </button>
      </div>

      {/* Read-only gate */}
      {!canEdit && (
        <div className="status-row status-warn" style={{ marginBottom:20 }}>
          <Icon.Warning/>
          Read-only mode -- set your steward identity in Settings to use the DQ Assistant.
        </div>
      )}

      {/* Stage indicator */}
      <StageIndicator stage={stage} onNavigateStage={setStage}/>

      <div {...dp}>
        {/* ---- STAGE 1: DEFINE ---- */}
        {stage >= 1 && (
          <div style={{ opacity: stage === 1 ? 1 : 0.5, pointerEvents: stage === 1 ? 'auto' : 'none' }}>
            <div className="card" style={{ borderColor: stage === 1 ? accentColor : 'var(--border)', marginBottom:24 }}>
              <div className="card-title">
                <span className="dot" style={{ background: stage === 1 ? accentColor : 'var(--text3)' }}/>
                1 &ndash; Define the rule
              </div>
              {stage === 1 && (
                <Stage1Panel
                  conversationMode={conversationMode}
                  onModeChange={setConversationMode}
                  ruleIntent={ruleIntent}
                  onRuleIntentChange={setRuleIntent}
                  selectedCdeIds={selectedCdeIds}
                  onCdeToggle={handleCdeToggle}
                  extraTableIds={extraTableIds}
                  onExtraTableToggle={handleExtraTableToggle}
                  suggestions={suggestions}
                  cdeSearch={cdeSearch}
                  onCdeSearch={setCdeSearch}
                  data={data || {}}
                  onBuild={handleBuild}
                  promptBuilt={!!builtPrompt}
                />
              )}
              {stage > 1 && ruleIntent && (
                <div style={{ fontSize:13, color:'var(--text2)', fontStyle:'italic',
                  display:'flex', alignItems:'center', gap:10 }}>
                  <span className="badge badge-green"><Icon.Check/> Done</span>
                  "{ruleIntent.length > 80 ? ruleIntent.substring(0, 80) + '...' : ruleIntent}"
                </div>
              )}
            </div>
          </div>
        )}

        {/* ---- STAGE 2: PROMPT ---- */}
        {stage >= 2 && (
          <div style={{ opacity: stage === 2 ? 1 : 0.5, pointerEvents: stage === 2 ? 'auto' : 'none' }}>
            <div className="card" style={{ borderColor: stage === 2 ? accentColor : 'var(--border)', marginBottom:24 }}>
              <div className="card-title">
                <span className="dot" style={{ background: stage === 2 ? accentColor : 'var(--text3)' }}/>
                2 &ndash; Copy prompt to AI
              </div>
              {stage === 2 && (
                <Stage2Panel
                  builtPrompt={builtPrompt}
                  contextSummary={contextSummary}
                  onCopy={handleCopy}
                  copyConfirmed={copyConfirmed}
                  onBack={() => setStage(1)}
                />
              )}
              {stage > 2 && (
                <div style={{ fontSize:13, color:'var(--text2)', display:'flex', alignItems:'center', gap:10 }}>
                  <span className="badge badge-green"><Icon.Check/> Done</span>
                  Prompt copied to clipboard
                </div>
              )}
            </div>
          </div>
        )}

        {/* ---- STAGE 3: PASTE ---- */}
        {stage >= 3 && (
          <div style={{ opacity: stage === 3 ? 1 : 0.5, pointerEvents: stage === 3 ? 'auto' : 'none' }}>
            <div className="card" style={{ borderColor: stage === 3 ? accentColor : 'var(--border)', marginBottom:24 }}>
              <div className="card-title">
                <span className="dot" style={{ background: stage === 3 ? accentColor : 'var(--text3)' }}/>
                3 &ndash; Paste AI output
              </div>
              {stage === 3 && (
                <Stage3Panel
                  pasteText={pasteText}
                  onPasteChange={setPasteText}
                  onParse={handleParse}
                  parseResult={parseResult}
                  onAddContextCopy={handleAddContextCopy}
                  data={data || {}}
                  extraTableIds={extraTableIds}
                  onExtraTableToggle={handleExtraTableToggle}
                  onRegeneratePrompt={() => { setStage(2); }}
                />
              )}
              {stage > 3 && proposals.length > 0 && (
                <div style={{ fontSize:13, color:'var(--text2)', display:'flex', alignItems:'center', gap:10 }}>
                  <span className="badge badge-green"><Icon.Check/> Done</span>
                  {proposals.filter(p => !p.committed).length} proposal(s) ready to review
                </div>
              )}
            </div>
          </div>
        )}

        {/* ---- STAGE 4: COMMIT ---- */}
        {stage >= 4 && (
          <div>
            <div className="card" style={{ borderColor: stage === 4 ? accentColor : 'var(--border)' }}>
              <div className="card-title">
                <span className="dot" style={{ background: stage === 4 ? accentColor : 'var(--text3)' }}/>
                4 &ndash; Review and commit
              </div>
              <Stage4Panel
                proposals={proposals}
                validations={validations}
                onCommit={handleCommit}
                onRefine={handleRefine}
                onUpdate={handleUpdateProposal}
                onDiscard={handleDiscardProposal}
                data={data || {}}
              />
            </div>
          </div>
        )}

        {/* Show stage 3 prompt when on stage 2 (visible but muted) */}
        {stage === 2 && (
          <div style={{ opacity:0.4, pointerEvents:'none' }}>
            <div className="card" style={{ marginBottom:24 }}>
              <div className="card-title">
                <span className="dot" style={{ background:'var(--text3)' }}/>
                3 &ndash; Paste AI output
              </div>
              <div style={{ fontSize:12, color:'var(--text3)' }}>
                Complete Step 2 first -- copy the prompt and run your AI conversation.
              </div>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
