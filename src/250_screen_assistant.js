function suggestCdes(ruleIntentText, data) {
  if (!ruleIntentText || !data) return [];
  const cdes = (data.critical_data_element || []).filter(c => !c.retiring_timestamp);
  const tokens = ruleIntentText.toLowerCase().split(/[^a-z]+/).filter(t => t.length >= 3);
  if (tokens.length === 0) return [];
  const scored = cdes.map(cde => {
    const hay = [
      cde.source_field_name        || '',
      cde.source_table_name        || '',
      cde.source_system_name       || '',
      cde.source_database_name     || '',
      cde.data_element_definition  || '',
      cde.data_element_explanation || '',
    ].join(' ').toLowerCase();
    const score = tokens.reduce((s, t) => s + (hay.includes(t) ? 1 : 0), 0);
    return { cde, score };
  });
  return scored
    .filter(s => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 8)
    .map(s => s.cde);
}

