function buildRuleIntentSection(ruleIntent, selectedCdeIds, data) {
  const lines = [
    '## RULE TO FORMALISE',
    '',
    'The steward has described the following business rule in their own words:',
    '',
    '"' + ruleIntent + '"',
    '',
  ];
  const cdes = (data.critical_data_element || []).filter(c => !c.retiring_timestamp);
  if (selectedCdeIds && selectedCdeIds.length > 0) {
    lines.push('The steward believes this rule relates to the following data fields:');
    selectedCdeIds.forEach(id => {
      const cde = cdes.find(c => c.critical_data_element_id === id);
      if (cde) {
        lines.push('- ' + (cde.source_field_name || 'unknown') + ' (' + (cde.source_table_name || 'unknown') + ')');
      }
    });
  } else {
    lines.push('The steward has not identified a specific data field yet. As part of the conversation,');
    lines.push('help identify which field(s) this rule should apply to, then confirm with the steward.');
  }
  lines.push('');
  lines.push('---');
  lines.push('');
  return lines.join('\n');
}

function buildCdeSection(selectedCdeIds, conversationMode, data) {
  const cdes = (data.critical_data_element || []).filter(c => !c.retiring_timestamp);
  const lines = [
    '## CONTEXT: DATA FIELDS IN SCOPE',
    '',
  ];
  if (selectedCdeIds && selectedCdeIds.length > 0) {
    selectedCdeIds.forEach(id => {
      const cde = cdes.find(c => c.critical_data_element_id === id);
      if (!cde) return;
      lines.push('### Field: ' + (cde.source_field_name || 'not specified'));
      lines.push('Table:           ' + (cde.source_table_name        || 'not specified'));
      lines.push('Database:        ' + (cde.source_database_name     || 'not specified'));
      lines.push('System:          ' + (cde.source_system_name       || 'not specified'));
      lines.push('Platform:        ' + (cde.source_platform_name     || 'not specified'));
      lines.push('Definition:      ' + (cde.data_element_definition  || 'not specified'));
      lines.push('Explanation:     ' + (cde.data_element_explanation || 'not specified'));
      lines.push('Snapshot filter: ' + (cde.source_snapshot_filter   || 'not specified'));
      lines.push('Internal ID:     ' + cde.critical_data_element_id);
      lines.push('');
    });
  } else {
    lines.push('### All registered data fields (identify the relevant one(s) during the conversation)');
    const rows = cdes.slice(0, 50);
    rows.forEach(cde => {
      lines.push(
        cde.critical_data_element_id + ' | ' +
        (cde.source_field_name    || '') + ' | ' +
        (cde.source_table_name    || '') + ' | ' +
        (cde.source_system_name   || '')
      );
    });
    lines.push('');
  }
  lines.push('---');
  lines.push('');
  return lines.join('\n');
}

function buildSchemaSection(selectedCdeIds, extraTableIds, conversationMode, data) {
  const cdes  = (data.critical_data_element || []).filter(c => !c.retiring_timestamp);
  const ddls  = (data.source_table_ddl      || []).filter(d => !d.retiring_timestamp);
  const lines = ['## CONTEXT: TABLE STRUCTURE', ''];

  const primaryTableNames = new Set();
  if (selectedCdeIds && selectedCdeIds.length > 0) {
    selectedCdeIds.forEach(id => {
      const cde = cdes.find(c => c.critical_data_element_id === id);
      if (cde && cde.source_table_name) primaryTableNames.add(cde.source_table_name);
    });
  }

  const addedDdlIds = new Set();

  primaryTableNames.forEach(tblName => {
    const ddl = ddls.find(d => d.source_table_name === tblName);
    if (ddl) {
      addedDdlIds.add(ddl.source_table_ddl_id);
      const label = conversationMode === 'technical'
        ? '(primary -- referenced by selected CDE)'
        : '(contains the field in scope)';
      lines.push('### ' + tblName + ' ' + label);
      let cols = [];
      try { cols = ddl.parsed_columns ? JSON.parse(ddl.parsed_columns) : []; } catch {}
      if (cols.length > 0) {
        cols.forEach(c => { lines.push(c.name + '  ' + c.type); });
      } else if (ddl.ddl_text) {
        lines.push('[DDL text available but not yet parsed -- parse via Physical Layer screen]');
      }
      lines.push('');
    } else {
      lines.push('### ' + tblName + ' (contains the field in scope)');
      lines.push('No DDL registered. Add DDL via the Physical Layer screen to provide schema context.');
      lines.push('');
    }
  });

  if (extraTableIds && extraTableIds.length > 0) {
    extraTableIds.forEach(id => {
      const ddl = ddls.find(d => d.source_table_ddl_id === id);
      if (!ddl || addedDdlIds.has(id)) return;
      addedDdlIds.add(id);
      lines.push('### ' + ddl.source_table_name + ' (related table)');
      let cols = [];
      try { cols = ddl.parsed_columns ? JSON.parse(ddl.parsed_columns) : []; } catch {}
      if (cols.length > 0) {
        lines.push('Columns: ' + cols.map(c => c.name).join(', '));
      }
      lines.push('');
    });
  }

  if (primaryTableNames.size === 0 && (!extraTableIds || extraTableIds.length === 0)) {
    lines.push('No data fields selected and no supplementary tables added.');
    lines.push('Add CDEs or supplementary tables to include schema context.');
    lines.push('');
  }

  lines.push('---');
  lines.push('');
  return lines.join('\n');
}

function buildProfilingSection(selectedCdeIds, data, compressed) {
  const cdes     = (data.critical_data_element || []).filter(c => !c.retiring_timestamp);
  const profiling = data.field_profiling || [];
  const lines    = ['## CONTEXT: DATA PROFILING', ''];

  if (!selectedCdeIds || selectedCdeIds.length === 0) {
    lines.push('No data fields selected. Profiling context is not available.');
    lines.push('');
    lines.push('---');
    lines.push('');
    return lines.join('\n');
  }

  const addedTables = new Set();
  let anyProfileFound = false;

  selectedCdeIds.forEach(id => {
    const cde = cdes.find(c => c.critical_data_element_id === id);
    if (!cde) return;
    const tblKey = (cde.source_database_name || '') + '|||' + (cde.source_table_name || '');
    if (addedTables.has(tblKey)) return;
    addedTables.add(tblKey);

    const tableProfiles = profiling.filter(p =>
      !p.retiring_timestamp &&
      p.source_database_name === cde.source_database_name &&
      p.source_table_name    === cde.source_table_name
    );

    lines.push('### ' + (cde.source_table_name || 'unknown'));
    if (tableProfiles.length === 0) {
      lines.push('No profiling data is available for this table yet. If statistics would help define');
      lines.push('a realistic threshold, ask the steward or capture profiling via the DDL screen.');
      lines.push('');
      return;
    }

    anyProfileFound = true;
    tableProfiles.forEach(p => {
      lines.push('Field: ' + (p.source_field_name || 'unknown'));
      if (p.summary_raw && !compressed) {
        lines.push(p.summary_raw);
      }
      if (!compressed && p.top_values_raw) {
        lines.push('Top values:');
        lines.push(p.top_values_raw);
      }
      if (!compressed && p.profiling_notes) {
        lines.push('Notes: ' + p.profiling_notes);
      }
      lines.push('');
    });
  });

  if (!anyProfileFound) {
    lines.push('No profiling data is available for the selected fields.');
    lines.push('');
  }

  lines.push('---');
  lines.push('');
  return lines.join('\n');
}

function buildDimensionsSection(conversationMode, data) {
  const dims  = (data.quality_dimension || []).filter(d => !d.retiring_timestamp);
  const lines = [];

  if (conversationMode === 'technical') {
    lines.push('## CONTEXT: QUALITY DIMENSIONS');
    lines.push('');
  } else {
    lines.push('## CONTEXT: TYPES OF DATA QUALITY CHECK');
    lines.push('');
    lines.push('The following types of data quality check are used in this programme. Each rule you');
    lines.push('define will be categorised under one of these types. During the conversation,');
    lines.push('identify which type best describes the rule the steward has in mind.');
    lines.push('');
  }

  dims.forEach(d => {
    lines.push(d.quality_dimension_id + ' | ' + (d.dimension_name || '') +
      (d.dimension_acronymn ? ' (' + d.dimension_acronymn + ')' : ''));
  });

  lines.push('');
  lines.push('---');
  lines.push('');
  return lines.join('\n');
}

function buildExistingRulesSection(selectedCdeIds, conversationMode, data) {
  const allocs = data.data_quality_rule_allocation || [];
  const rules  = data.data_quality_rule            || [];
  const dims   = data.quality_dimension            || [];
  const lines  = [];

  let relevant = [];
  if (selectedCdeIds && selectedCdeIds.length > 0) {
    relevant = allocs.filter(a =>
      !a.retiring_timestamp &&
      selectedCdeIds.includes(a.critical_data_element_id)
    );
  }

  if (conversationMode === 'technical') {
    lines.push('## CONTEXT: EXISTING RULES ON THESE CDEs');
    lines.push('');
    if (relevant.length === 0) {
      lines.push('No rules are currently allocated to these CDEs.');
    } else {
      lines.push('The following rules are already in place. Do not reproduce these.');
      lines.push('');
      relevant.forEach(a => {
        const rule = rules.find(r => r.data_quality_rule_id === a.data_quality_rule_id);
        const dim  = dims.find(d => d.quality_dimension_id  === a.quality_dimension_id);
        if (!rule) return;
        lines.push('Rule: ' + rule.rule_name + ' | Dimension: ' + (dim ? dim.dimension_name : 'unknown'));
        if (rule.sql_code) {
          const sql = rule.sql_code.length > 200 ? rule.sql_code.substring(0, 200) + '...' : rule.sql_code;
          lines.push('SQL: ' + sql);
        }
        lines.push('---');
      });
    }
  } else {
    lines.push('## CONTEXT: EXISTING CHECKS ON THESE FIELDS');
    lines.push('');
    if (relevant.length === 0) {
      lines.push('No quality checks are currently registered for these fields.');
    } else {
      lines.push('The following data quality checks are already in place for these fields.');
      lines.push('Do not reproduce these. Identify new checks that complement the existing ones.');
      lines.push('');
      relevant.forEach(a => {
        const rule = rules.find(r => r.data_quality_rule_id === a.data_quality_rule_id);
        const dim  = dims.find(d => d.quality_dimension_id  === a.quality_dimension_id);
        if (!rule) return;
        lines.push('Check: ' + rule.rule_name + ' (' + (dim ? dim.dimension_name : 'unknown') + ')');
        if (rule.rule_explanation) lines.push('Description: ' + rule.rule_explanation);
        lines.push('---');
      });
    }
  }

  lines.push('');
  lines.push('---');
  lines.push('');
  return lines.join('\n');
}

function buildConversationInstructionsSection(conversationMode) {
  if (conversationMode === 'technical') {
    return [
      '## CONVERSATION INSTRUCTIONS',
      '',
      'Follow this process:',
      '',
      '1. Read the steward\'s rule description and the context carefully.',
      '2. Ask up to 3 targeted clarifying questions before drafting SQL. Focus on:',
      '   - The exact failure condition (null? wrong format? out of range? referential mismatch?)',
      '   - Whether the rule applies to all records or a subset',
      '   - How strict the threshold should be',
      '3. Identify the quality dimension and confirm with the steward.',
      '4. Draft the SQL rule. Show it to the steward and explain what it checks.',
      '   Ask for technical feedback and iterate if needed.',
      '5. Confirm the SQL and threshold before producing the formal proposal.',
      '6. Produce the rule proposal in the exact format below.',
      '',
      'You may produce multiple proposals if the steward\'s description implies more than one rule.',
      '',
      '---',
      '',
    ].join('\n');
  }
  return [
    '## CONVERSATION INSTRUCTIONS',
    '',
    'Follow this process carefully. The steward is a business expert, not a technical one.',
    'Your job is to translate their business knowledge into a precise quality rule.',
    '',
    'Step 1 -- Understand the rule intent',
    '  Ask up to 3 targeted clarifying questions to understand:',
    '  - What does a "bad" record look like? (missing value? wrong value? impossible value?)',
    '  - Does the rule apply to all records or only certain ones?',
    '  - Are there any known exceptions or edge cases?',
    '  Keep questions short and in plain language. Avoid technical jargon.',
    '',
    'Step 2 -- Identify the quality dimension',
    '  Tell the steward which type of data quality check this is (from the list above) and',
    '  explain in one sentence why. Confirm they agree before moving on.',
    '  Example: "This sounds like a Completeness issue -- we are checking that a required field',
    '  always has a value. Does that match your understanding?"',
    '',
    'Step 3 -- Confirm the rule in plain language',
    '  Write a precise, unambiguous description of the rule in plain English. This should be',
    '  specific enough that a colleague could apply it manually to a record.',
    '  Example: "Every prisoner record must have a date of birth recorded, and that date must',
    '  be in the past. Records where date of birth is blank, or where it falls on or after',
    '  today\'s date, will fail this check."',
    '  Ask the steward to confirm this accurately captures their intent.',
    '',
    'Step 4 -- Provide concrete examples',
    '  Give 2 to 3 specific examples of records that would FAIL this check.',
    '  Describe them in the steward\'s domain language, not database terms.',
    '  Example: "A prisoner record showing date of birth as 01/01/2040 would fail.',
    '  A record with no date of birth recorded would also fail."',
    '  Ask the steward to confirm these examples make sense.',
    '',
    'Step 5 -- Agree the pass threshold',
    '  Propose a pass threshold in business terms.',
    '  Example: "Based on the data profiling, around 2% of records currently have this issue.',
    '  Should we set the target so that 99 out of every 100 records must pass this check?',
    '  Or would you like a stricter target?"',
    '  Confirm the threshold with the steward.',
    '',
    'Step 6 -- Produce the proposal',
    '  Once the steward has confirmed the rule description, examples, and threshold, produce',
    '  the structured proposal in the format below. Generate the SQL internally without showing',
    '  it to the steward during the conversation.',
    '',
    'You may produce multiple proposals if the conversation reveals more than one distinct rule.',
    '',
    '---',
    '',
  ].join('\n');
}

function buildOutputFormatSection(conversationMode) {
  const intro = [
    '## OUTPUT FORMAT',
    '',
    'When you are ready to produce the formal rule proposal, output it in this exact format.',
    'Do not change the delimiter lines. Do not add text between START and END.',
    'You may produce multiple blocks if more than one rule was identified.',
    '',
  ];

  const block = [
    '===RULE_PROPOSAL_START===',
    '{',
    '  "rule_name": "Short descriptive name written for a business audience",',
    '  "rule_explanation": "Plain English explanation of what the rule checks and why it matters",',
    '  "rule_narrative": "Precise plain language statement of the rule confirmed with the steward",',
    '  "rule_examples": [',
    '    "Example of a record that would FAIL: [description]",',
    '    "Example of a record that would FAIL: [description]"',
    '  ],',
    '  "sql_code": "Full SQL implementing the rule -- must produce a pass rate between 0 and 1",',
    '  "sql_code_sample": "Optional: simplified SQL for technical reference",',
    '  "quality_dimension_id": 0,',
    '  "cde_id": 0,',
    '  "cde_suggestion": "If cde_id is null: field name and table you believe this applies to",',
    '  "bumper_value": 0.99,',
    '  "frequency": "daily",',
    '  "automated": true,',
    '  "steward_notes": "Any caveats, assumptions, or points for the steward to be aware of"',
    '}',
    '===RULE_PROPOSAL_END===',
  ];

  if (conversationMode !== 'technical') {
    return intro.concat([
      'Replace the placeholder values above with the actual values for this rule.',
      'quality_dimension_id must be an integer from the dimension list above.',
      'cde_id must be an integer from the data fields list above, or null if not pre-selected.',
      'bumper_value is a decimal between 0 and 1 (e.g. 0.99 means 99 in 100 records must pass).',
      '',
    ]).concat(block).join('\n');
  }
  return intro.concat(block).join('\n');
}

function buildAssistantPrompt(ruleIntent, selectedCdeIds, extraTableIds, conversationMode, data) {
  const mode = conversationMode || 'business';

  const sections = [
    buildHeaderSection(mode),
    buildRoleSection(),
    buildConversationModeSection(mode),
    buildRuleIntentSection(ruleIntent, selectedCdeIds, data),
    buildCdeSection(selectedCdeIds, mode, data),
    buildSchemaSection(selectedCdeIds, extraTableIds, mode, data),
    buildProfilingSection(selectedCdeIds, data, false),
    buildDimensionsSection(mode, data),
    buildExistingRulesSection(selectedCdeIds, mode, data),
    buildConversationInstructionsSection(mode),
    buildOutputFormatSection(mode),
  ];

  let promptText = sections.join('');
  const charCount = promptText.length;

  // Truncation: if over 6000 chars, rebuild with compressed profiling
  if (charCount > 6000) {
    const compressed = [
      buildHeaderSection(mode),
      buildRoleSection(),
      buildConversationModeSection(mode),
      buildRuleIntentSection(ruleIntent, selectedCdeIds, data),
      buildCdeSection(selectedCdeIds, mode, data),
      buildSchemaSection(selectedCdeIds, extraTableIds, mode, data),
      buildProfilingSection(selectedCdeIds, data, true),
      buildDimensionsSection(mode, data),
      buildExistingRulesSection(selectedCdeIds, mode, data),
      buildConversationInstructionsSection(mode),
      buildOutputFormatSection(mode),
    ].join('');
    if (compressed.length < charCount) promptText = compressed;
  }

  const finalCount = promptText.length;
  const truncated  = finalCount < charCount;

  // Context summary for UI display
  const selCdes = selectedCdeIds || [];
  const cdes    = (data.critical_data_element || []).filter(c => !c.retiring_timestamp);
  const tableNames = new Set();
  selCdes.forEach(id => {
    const cde = cdes.find(c => c.critical_data_element_id === id);
    if (cde && cde.source_table_name) tableNames.add(cde.source_table_name);
  });
  (extraTableIds || []).forEach(id => {
    const ddl = (data.source_table_ddl || []).find(d => d.source_table_ddl_id === id);
    if (ddl && ddl.source_table_name) tableNames.add(ddl.source_table_name);
  });

  const contextSummary = {
    cdeCount:           selCdes.length,
    tableCount:         tableNames.size,
    dimensionCount:     (data.quality_dimension || []).filter(d => !d.retiring_timestamp).length,
    truncated:          truncated,
    veryLarge:          finalCount > 10000,
    conversationMode:   mode,
    cdeNames:           selCdes.map(id => {
      const c = cdes.find(x => x.critical_data_element_id === id);
      return c ? (c.source_field_name + ' (' + c.source_table_name + ')') : ('ID ' + id);
    }),
    tableNamesList:     Array.from(tableNames),
    dimensionNames:     (data.quality_dimension || [])
      .filter(d => !d.retiring_timestamp)
      .map(d => d.dimension_name),
  };

  return { promptText, characterCount: finalCount, contextSummary };
}

